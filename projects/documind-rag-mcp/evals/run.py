#!/usr/bin/env python3
"""Secret-free, pytest-compatible DocuMind evaluation harness."""
from __future__ import annotations
import asyncio, json, sys
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol
from uuid import uuid4

ROOT=Path(__file__).resolve().parents[1]
BACKEND=ROOT/"backend"
sys.path.insert(0,str(BACKEND));sys.path.insert(0,str(ROOT/"scripts"))
from app.domain.retrieval_shaping import shape_retrieval
from app.providers.deterministic import DeterministicChatProvider,DeterministicEmbeddingProvider
from app.repositories.memory import MemoryChunkRepository,MemoryConversationRepository,MemoryDocumentRepository,MemoryRetrievalLogRepository,MemoryStorageRepository
from app.services.chat import ChatService
from app.services.documents import DocumentService
from make_sample_pdfs import main as make_samples

class FaithfulnessJudge(Protocol):
    def score(self,answer:str,contexts:list[str],grounded:bool)->float: ...
class DeterministicFaithfulnessJudge:
    """Offline judge: a grounded answer must be a substring of retrieved context."""
    def score(self,answer:str,contexts:list[str],grounded:bool)->float:
        if not grounded:return 1.0
        claim=answer.removeprefix("According to the document: ").strip().lower()
        return 1.0 if any(claim in c.lower() for c in contexts) else 0.0
@dataclass
class Row:
    id:str; retrieval_hit:float; faithfulness:float; citation_accuracy:float; refusal_correct:float|None

async def evaluate()->list[Row]:
    make_samples()
    documents=MemoryDocumentRepository();chunks=MemoryChunkRepository(documents);conversations=MemoryConversationRepository();logs=MemoryRetrievalLogRepository();storage=MemoryStorageRepository();embeddings=DeterministicEmbeddingProvider()
    document_service=DocumentService(documents,chunks,storage,embeddings,pages_per_batch=3)
    chat_service=ChatService(conversations,chunks,logs,embeddings,DeterministicChatProvider(),similarity_threshold=.10)
    session=uuid4();doc_ids={}
    for path in sorted((ROOT/"sample_docs").glob("*.pdf")):
        doc=await document_service.upload(session,path.name,"application/pdf",path.read_bytes())
        while doc.status.value not in {"ready","failed"}:doc=await document_service.process_batch(doc.id,session)
        if doc.status.value!="ready":raise RuntimeError(f"sample processing failed: {doc.filename}: {doc.processing_error}")
        doc_ids[path.name]=doc.id
    cases=[json.loads(line) for line in (ROOT/"evals/golden.jsonl").read_text().splitlines() if line.strip()]
    judge=DeterministicFaithfulnessJudge();rows=[]
    for case in cases:
        filters=[doc_ids[case["document"]]] if case["document"] else list(doc_ids.values())
        query=await embeddings.embed_query(case["question"])
        raw=await chunks.match(query,8,.10,session,filters)
        evidence=shape_retrieval(raw,4000)
        conversation=await chat_service.start_conversation(session)
        _,answer=await chat_service.ask(conversation.id,session,case["question"],filters)
        evidence_ids={c.chunk_id for c in evidence}
        hit=1.0 if (not case["answerable"] or any(c.page_number==case["gold_page"] and c.document_id in filters for c in evidence)) else 0.0
        accuracy=(sum(c.chunk_id in evidence_ids for c in answer.citations)/len(answer.citations)) if answer.citations else (1.0 if not answer.grounded else 0.0)
        refusal=(1.0 if not answer.grounded else 0.0) if not case["answerable"] else None
        rows.append(Row(case["id"],hit,judge.score(answer.answer,[c.content for c in evidence],answer.grounded),accuracy,refusal))
    return rows

def render(rows:list[Row])->str:
    answerable=[r for r in rows if r.refusal_correct is None];unanswerable=[r for r in rows if r.refusal_correct is not None]
    avg=lambda values:sum(values)/len(values) if values else 0.0
    metrics={"retrieval_hit":avg([r.retrieval_hit for r in answerable]),"faithfulness":avg([r.faithfulness for r in rows]),"citation_accuracy":avg([r.citation_accuracy for r in rows]),"refusal_correctness":avg([r.refusal_correct for r in unanswerable if r.refusal_correct is not None])}
    lines=["| Metric | Score | Cases |","|---|---:|---:|",f"| Retrieval hit | {metrics['retrieval_hit']:.0%} | {len(answerable)} |",f"| Faithfulness (offline judge) | {metrics['faithfulness']:.0%} | {len(rows)} |",f"| Citation accuracy | {metrics['citation_accuracy']:.0%} | {len(rows)} |",f"| Refusal correctness | {metrics['refusal_correctness']:.0%} | {len(unanswerable)} |"]
    return "\n".join(lines)

async def main()->None:
    rows=await evaluate();table=render(rows);print(table)
    output="# Evaluation\n\nGenerated by `python evals/run.py` using deterministic local providers; no external LLM or credentials were used. The offline faithfulness judge checks that the answer claim is copied from retrieved context. This is reproducible regression evidence, not a substitute for a human or live-model judge.\n\n"+table+"\n\n## Dataset\n\n15 authored cases over three fictional PDFs: 10 answerable questions with gold pages and 5 deliberately unanswerable questions.\n\n## Limitations\n\nScores describe this frozen sample only. Live Gemini/Groq embeddings and generation require a separate credentialed evaluation before production claims.\n"
    (ROOT/"docs/evaluation.md").write_text(output)

if __name__=="__main__":asyncio.run(main())
